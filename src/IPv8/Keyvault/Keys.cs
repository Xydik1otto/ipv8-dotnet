using System;
using System.Security.Cryptography;
using Org.BouncyCastle.Crypto.Parameters;
using Org.BouncyCastle.Crypto.Signers;
using Org.BouncyCastle.Crypto.Agreement;
using Org.BouncyCastle.Security;

namespace IPv8.Keyvault
{
    /// <summary>
    /// Interface for a public or private key (port of ipv8/keyvault/keys.py).
    /// </summary>
    public abstract class Key
    {
        /// <summary>Return the public key for this key material.</summary>
        public abstract PublicKey Pub();

        /// <summary>Whether this key material includes a secret key.</summary>
        public abstract bool HasSecretKey { get; }

        /// <summary>Convert this key material to bytes.</summary>
        public abstract byte[] KeyToBin();

        /// <summary>Get the SHA-1 hash of this key.</summary>
        public byte[] KeyToHash()
        {
            return HasSecretKey ? Util.Sha1(Pub().KeyToBin()) : Util.Sha1(KeyToBin());
        }
    }

    /// <summary>Interface for a private key.</summary>
    public abstract class PrivateKey : Key
    {
        public override bool HasSecretKey => true;

        /// <summary>Create a signature for the given data.</summary>
        public abstract byte[] Signature(byte[] msg);

        /// <summary>
        /// Perform a Diffie-Hellman key exchange with the given peer public key bytes.
        /// Returns the shared secret as bytes.
        /// </summary>
        public abstract byte[] DiffieHellman(byte[] peerPublicKey);

        /// <summary>
        /// Return the raw public key bytes suitable for encryption/DH (e.g., X25519 bytes).
        /// </summary>
        public abstract byte[] GetCryptPk();
    }

    /// <summary>Interface for a public key.</summary>
    public abstract class PublicKey : Key
    {
        /// <summary>We are already the public key, return ourselves.</summary>
        public override PublicKey Pub() => this;

        /// <summary>A public key cannot be assumed to include private key material.</summary>
        public override bool HasSecretKey => false;

        /// <summary>Verify that the given signature belongs to the given message for this public key.</summary>
        public abstract bool Verify(byte[] signature, byte[] msg);

        /// <summary>Get the length (in number of bytes) for signatures generated by this type of key.</summary>
        public abstract int GetSignatureLength();

        /// <summary>
        /// Return the raw public key bytes suitable for encryption/DH (e.g., X25519 bytes).
        /// </summary>
        public abstract byte[] GetCryptPk();

        /// <summary>Return the string name of the curve used by this key (e.g., 'curve25519').</summary>
        public abstract string CurveName();
    }

    /// <summary>
    /// A LibNaCL "dual key" public key: 'LibNaCLPK:' (10 B) + X25519 public (32 B) + Ed25519 public (32 B).
    /// Binary format source of truth: ipv8-rust-tunnels/src/keys.rs.
    /// </summary>
    public sealed class LibNaclPublicKey : PublicKey
    {
        public const string PrefixText = "LibNaCLPK:";
        public static readonly byte[] Prefix = Util.Utf8(PrefixText);

        private readonly byte[] _cryptPk;    // 32-byte X25519 public key
        private readonly Ed25519PublicKeyParameters _edPub; // 32-byte Ed25519 public key

        public LibNaclPublicKey(byte[] keystring)
        {
            if (keystring == null || keystring.Length < 74 || !Util.StartsWith(keystring, Prefix))
            {
                throw new ArgumentException(
                    $"Public key is not a LibNaCLPK key ({(keystring == null ? "null" : keystring.Length)} bytes)");
            }
            _cryptPk = Util.Slice(keystring, 10, 32);
            var vkBytes = Util.Slice(keystring, 42, 32);
            _edPub = new Ed25519PublicKeyParameters(vkBytes, 0);
        }

        public LibNaclPublicKey(byte[] cryptPk, byte[] edPublicKey)
        {
            if (cryptPk.Length != 32 || edPublicKey.Length != 32)
            {
                throw new ArgumentException("LibNaCLPK key parts must be 32 bytes each");
            }
            _cryptPk = Util.CopyOf(cryptPk);
            _edPub = new Ed25519PublicKeyParameters(edPublicKey, 0);
        }

        public override byte[] KeyToBin()
        {
            // keys.rs: [b"LibNaCLPK:", crypt_pk, &vk].concat()
            return Util.Concat(Prefix, _cryptPk, _edPub.GetEncoded());
        }

        public override bool Verify(byte[] signature, byte[] msg)
        {
            try
            {
                var signer = new Ed25519Signer();
                signer.Init(false, _edPub);
                signer.BlockUpdate(msg, 0, msg.Length);
                return signer.VerifySignature(signature);
            }
            catch (Exception)
            {
                return false;
            }
        }

        public override int GetSignatureLength() => 64;

        public override byte[] GetCryptPk() => Util.CopyOf(_cryptPk);

        public override string CurveName() => "curve25519";
    }

    /// <summary>
    /// A LibNaCL "dual key" private key: 'LibNaCLSK:' (10 B) + X25519 private (32 B) + Ed25519 seed (32 B).
    /// Binary format source of truth: ipv8-rust-tunnels/src/keys.rs.
    /// </summary>
    public sealed class LibNaclPrivateKey : PrivateKey
    {
        public const string PrefixText = "LibNaCLSK:";
        public static readonly byte[] Prefix = Util.Utf8(PrefixText);

        private readonly byte[] _cryptSk; // 32-byte X25519 private key
        private readonly Ed25519PrivateKeyParameters _edPriv; // Ed25519 seed

        public LibNaclPrivateKey(byte[] keystring)
        {
            if (keystring == null || keystring.Length < 74 || !Util.StartsWith(keystring, Prefix))
            {
                throw new ArgumentException(
                    $"Private key is not a LibNaCLSK key ({(keystring == null ? "null" : keystring.Length)} bytes)");
            }
            _cryptSk = Util.Slice(keystring, 10, 32);
            var signerSeed = Util.Slice(keystring, 42, 32);
            _edPriv = new Ed25519PrivateKeyParameters(signerSeed, 0);
        }

        /// <summary>Generate a new curve25519 dual key (Ed25519 signer + X25519 crypt key).</summary>
        public LibNaclPrivateKey(SecureRandom? random)
        {
            var rng = random ?? new SecureRandom();
            _edPriv = new Ed25519PrivateKeyParameters(rng);
            _cryptSk = new X25519PrivateKeyParameters(rng).GetEncoded();
        }

        public override PublicKey Pub()
        {
            // keys.rs: crypt_pk derived from crypt_sk (if present), vk derived from the signer key.
            var xPublicKey = new X25519PrivateKeyParameters(_cryptSk, 0).GeneratePublicKey();
            return new LibNaclPublicKey(xPublicKey.GetEncoded(), _edPriv.GeneratePublicKey().GetEncoded());
        }

        public override byte[] KeyToBin()
        {
            // keys.rs: [b"LibNaCLSK:", sk, &seed].concat()
            return Util.Concat(Prefix, _cryptSk, _edPriv.GetEncoded());
        }

        public override byte[] Signature(byte[] msg)
        {
            var signer = new Ed25519Signer();
            signer.Init(true, _edPriv);
            signer.BlockUpdate(msg, 0, msg.Length);
            return signer.GenerateSignature();
        }

        public override byte[] DiffieHellman(byte[] peerPublicKey)
        {
            var agreement = new X25519Agreement();
            agreement.Init(new X25519PrivateKeyParameters(_cryptSk, 0));
            var shared = new byte[agreement.AgreementSize];
            agreement.CalculateAgreement(new X25519PublicKeyParameters(peerPublicKey, 0), shared, 0);
            return shared;
        }

        public override byte[] GetCryptPk() => Pub().GetCryptPk();
    }
}
